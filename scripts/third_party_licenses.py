"""Collect upstream license/notice files for every registry package in Cargo.lock.

Run `cargo fetch --locked`, then this script; use --check in CI. The inventory
deliberately includes build dependencies and dependencies of other platforms.
"""

import argparse
import hashlib
import os
from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = "THIRD_PARTY_LICENSES"
NOTICE_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "COPYRIGHT", "NOTICE", "UNLICENSE", "AUTHORS")
# These published crates omit license texts but explicitly offer Apache-2.0.
# Pin each exception so that an upstream packaging change requires review.
APACHE_FALLBACKS = {
    ("jni", "0.22.4"): "MIT OR Apache-2.0",
    ("jni-macros", "0.22.4"): "MIT OR Apache-2.0",
    ("jni-sys-macros", "0.4.1"): "MIT OR Apache-2.0",
    ("r-efi", "6.0.0"): "MIT OR Apache-2.0 OR LGPL-2.1-or-later",
    ("rmcp", "3.5.1"): "Apache-2.0",
    ("rustls-platform-verifier-android", "0.2.0"): "MIT OR Apache-2.0",
}


def generate(root=ROOT, registry=None):
    if registry is None:
        registry = Path(os.environ.get("CARGO_HOME", Path.home() / ".cargo")) / "registry" / "src"
    lock_bytes = (root / "Cargo.lock").read_bytes()
    packages = tomllib.loads(lock_bytes.decode())["package"]
    sections = [
        "Temba — third-party Rust licenses and notices\n",
        "Generated by scripts/third_party_licenses.py; do not edit by hand.\n",
        f"Cargo.lock SHA256: {hashlib.sha256(lock_bytes).hexdigest()}\n\n",
        "Scope: all registry packages in Cargo.lock, including build and platform-specific\n"
        "dependencies. A listed package is not necessarily linked into every binary.\n"
        "Temba's own license is in LICENSE. Dependencies retain their own licenses.\n"
        "Upstream files are reproduced below; identical texts share one appendix entry.\n\n",
    ]
    texts = {}

    def entry(label, content):
        digest = hashlib.sha256(content.encode()).hexdigest()
        texts[digest] = content
        return f"  {label}: text {digest}\n"

    for package in sorted(packages, key=lambda p: (p["name"], p["version"])):
        if "source" not in package:
            continue
        if package["source"] != "registry+https://github.com/rust-lang/crates.io-index":
            raise ValueError(f"Review unsupported dependency source: {package['source']}")
        name, version = package["name"], package["version"]
        manifests = sorted(registry.glob(f"*/{name}-{version}/Cargo.toml"))
        if len(manifests) != 1:
            raise ValueError(f"Expected one cached source for {name} {version}; run cargo fetch --locked")
        directory = manifests[0].parent
        metadata = tomllib.loads(manifests[0].read_text(encoding="utf-8"))["package"]
        if metadata["name"] != name or metadata["version"] != version or not metadata.get("license"):
            raise ValueError(f"Missing or mismatched license metadata for {name} {version}")
        sections.append(f"\n{name} {version}\nLicense expression: {metadata['license']}\n"
                        f"Source: https://crates.io/crates/{name}/{version}\n")
        files = {p for p in directory.rglob("*")
                 if p.is_file() and p.name.upper().startswith(NOTICE_PREFIXES)}
        explicit = None
        if metadata.get("license-file"):
            explicit = (directory / metadata["license-file"]).resolve()
            if not explicit.is_relative_to(directory.resolve()) or not explicit.is_file():
                raise ValueError(f"Invalid license-file for {name} {version}")
            files.add(explicit)
        license_files = [p for p in files if p.name.upper().startswith(
            ("LICENSE", "LICENCE", "COPYING", "UNLICENSE"))]
        if not license_files and explicit is None:
            if APACHE_FALLBACKS.get((name, version)) != metadata["license"]:
                raise ValueError(f"No upstream license text for {name} {version}; review before releasing")
            sections.append("Selected license: Apache-2.0 (text omitted from the published crate).\n")
            sections.append(entry("Apache-2.0", (root / "scripts/licenses/Apache-2.0.txt").read_text(encoding="utf-8")))
        for path in sorted(files, key=lambda p: p.relative_to(directory).as_posix()):
            sections.append(entry(path.relative_to(directory).as_posix(), path.read_text(encoding="utf-8")))
    sections.append("\n\nLICENSE AND NOTICE TEXTS\n")
    for digest, content in sorted(texts.items()):
        sections.append(f"\n{'=' * 78}\nText {digest}\n{'=' * 78}\n{content}\n")
    return "".join(sections)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", type=Path, help="Cargo registry/src directory")
    parser.add_argument("--check", action="store_true", help="Fail if the committed document is stale")
    args = parser.parse_args()
    content = generate(registry=args.registry)
    destination = ROOT / OUTPUT
    if args.check:
        if not destination.exists() or destination.read_bytes() != content.encode("utf-8"):
            raise SystemExit("THIRD_PARTY_LICENSES is stale; run python scripts/third_party_licenses.py")
        print("Third-party licenses match Cargo.lock and cached upstream notices")
    else:
        destination.write_bytes(content.encode("utf-8"))
        print(f"Generated {destination.name}")


if __name__ == "__main__":
    main()
